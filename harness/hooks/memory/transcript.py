"""Shared helpers for the memory hooks. Standard library only.

Claude Code writes each session to a JSON-lines transcript. These helpers read the
conversation out of it: the person's words and the agent's text replies. Tool calls,
tool results, thinking, sub-agent (sidechain) lines, injected harness text and
scheduler prompts are dropped. The default is to drop anything not recognised.
"""
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

# Text the harness writes on the user side. None of it is the person typing.
INJECTED = (
    "<local-command-stdout>", "<local-command-stderr>", "<local-command-caveat>",
    "<command-message>", "<command-name>", "<command-args>",
    "<bash-input>", "<bash-stdout>", "<bash-stderr>",
    "<user-prompt-submit-hook>", "<session-start-hook>", "<post-tool-use-hook>",
    "<task-notification>", "<teammate-message", "[Request interrupted",
    "Caveat: The messages below were generated by the user",
)
# Scheduler prompts are the daemon, not a person.
SCHEDULED = ("[CRON FIRED",)
REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.DOTALL)
# The framework appends reply instructions after a wrapped message; they are not the person's words.
TRAILER = re.compile(r"\n(Reply using:|This is how Claude Code surfaces).*", re.DOTALL)


def read_hook_input():
    """The hook payload from stdin. Read it before anything else touches stdin."""
    raw = sys.stdin.buffer.read().decode("utf-8", "replace")
    if not raw.strip():
        return {}
    try:
        data = json.loads(raw)
    except ValueError:
        try:  # Windows can hand over lone backslashes in a path.
            data = json.loads(re.sub(r'(?<!\\)\\(?!["\\/bfnrtu])', r"\\\\", raw))
        except ValueError:
            return {}
    return data if isinstance(data, dict) else {}


def seat_dir(data):
    """The seat folder: CLAUDE_PROJECT_DIR, else the payload cwd, else the process cwd."""
    return Path(os.environ.get("CLAUDE_PROJECT_DIR") or data.get("cwd") or os.getcwd())


def utc_now():
    return datetime.now(timezone.utc)


def user_text(body):
    """A user-side message as the person wrote it, or "" when no person wrote it."""
    body = REMINDER.sub("", body).strip()
    if body.startswith(INJECTED) or body.startswith(SCHEDULED):
        return ""
    return TRAILER.sub("", body).strip()


def text_blocks(content):
    """Text out of a message. Every other block type is dropped."""
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    return "\n".join(b["text"] for b in content
                     if isinstance(b, dict) and b.get("type") == "text" and isinstance(b.get("text"), str))


def turns(path, max_bytes=8_000_000):
    """[(role, text)] in order, role "user" or "assistant". Reads at most the last max_bytes."""
    kept = []
    try:
        with open(path, "rb") as f:
            f.seek(0, 2)
            size = f.tell()
            f.seek(max(0, size - max_bytes))
            chunk = f.read().decode("utf-8", "replace")
    except OSError:
        return kept
    lines = chunk.splitlines()
    if size > max_bytes:
        lines = lines[1:]  # the first line is cut mid-record
    for raw in lines:
        raw = raw.strip()
        if not raw:
            continue
        try:
            event = json.loads(raw)
        except ValueError:
            continue
        if not isinstance(event, dict) or event.get("isSidechain") is True:
            continue
        # A message typed while a turn is running arrives as a queued-command attachment.
        att = event.get("attachment")
        if event.get("type") == "attachment" and isinstance(att, dict):
            if att.get("type") == "queued_command" and isinstance(att.get("prompt"), str):
                body = user_text(att["prompt"])
                if body:
                    kept.append(("user", body))
            continue
        if event.get("type") not in ("user", "assistant"):
            continue
        if event.get("toolUseResult") is not None or event.get("isMeta") is True or event.get("isCompactSummary") is True:
            continue
        msg = event.get("message")
        if not isinstance(msg, dict) or msg.get("role") not in ("user", "assistant"):
            continue
        body = text_blocks(msg.get("content")).strip()
        if msg["role"] == "user":
            body = user_text(body)
        if body:
            kept.append((msg["role"], body))
    return kept


def env_int(name, default):
    try:
        return int(os.environ.get(name, default))
    except ValueError:
        return default
